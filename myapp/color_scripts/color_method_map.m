function color = color_method_map(method)

    color_map = struct( ...
        'Parametric_FWER',              [0.65 0.71 0.99], ...
        'Parametric_FDR',               [0.02 0.71 0.84], ...
        'Size',                         [0.96 0.62 0.07], ...
        'Fast_TFCE',                    [0.29 0.85 0.55], ...
        'Constrained_FWER',             [0.99 0.45 0.45], ...
        'Constrained_FDR',              [0.85 0.29 0.75], ...
        'Omnibus_Multidimensional_cNBS',[0.99 0.85 0.25]  ...
    );

    if isfield(color_map, method)
        color = color_map.(method);
    else
        color = [0.7 0.7 0.7];  % fallback grey
    end
    
end